"""Regenerate the recorded teaching example; never runs during builds or page loads.

Run from the repository root: .venv/Scripts/python.exe scripts/generate_learning_demo.py
Requires the project's Python dependencies. Uses only bundled CIFAR-100 data.
"""
import base64
import asyncio
from datetime import datetime, timezone
import io
import json
import math
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["DLG_APP_MODE"] = "showcase"

import numpy as np
from PIL import Image
import torch
import app
from src.progress import reporter
from src.showcase import ShowcaseDataset
from src.utils import cross_entropy_for_onehot, get_image_transform, label_to_onehot, set_seed


def png(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def main():
    set_seed(50)
    image, label = ShowcaseDataset()[1]
    model = app.get_model(torch.device("cpu"))
    model.eval()
    data = get_image_transform()(image).unsqueeze(0)
    target = label_to_onehot(torch.tensor([label]), num_classes=100)
    loss = cross_entropy_for_onehot(model(data), target)
    # Every value of the first parameter's gradient, arranged into a compact map.
    gradient = torch.autograd.grad(loss, model.parameters())[0].detach().flatten().numpy()
    width = 32
    height = int(np.ceil(gradient.size / width))
    scale = max(float(np.abs(gradient).max()), 1e-12)
    normalized = np.zeros(width * height)
    normalized[:gradient.size] = gradient / scale
    normalized = normalized.reshape(height, width)
    neutral = np.array([237, 242, 244])
    positive = np.array([22, 100, 119])
    negative = np.array([47, 112, 187])
    color = np.where(normalized[..., None] >= 0, positive, negative)
    pixels = neutral + np.abs(normalized[..., None]) * (color - neutral)
    heatmap = Image.fromarray(pixels.astype(np.uint8))
    token = reporter.set(lambda event: None)
    try:
        result = asyncio.run(app.run_attack(app.AttackRequest(batch_size=1, image_indices=[1], device="cpu", num_iters=50)))
    finally:
        reporter.reset(token)
    assert result.success and len(result.reconstructed_images) == 1
    example = {
        "recordedAt": datetime.now(timezone.utc).isoformat(),
        "sampleId": 1, "name": "Dinossauro", "seed": 50, "iterations": 50,
        "device": "cpu", "batchSize": 1, "original": result.ground_truth_images[0],
        "reconstruction": result.reconstructed_images[0],
        "early": result.snapshot_images[0][0], "earlyIteration": result.snapshot_iterations[0],
        "gradient": png(heatmap),
        "metrics": {key: value if math.isfinite(value) else None for key, value in result.metrics.items()},
        "gradientNote": "Signed values of the first model parameter gradient, normalized by maximum absolute value; zero-padded to 32 columns. Not an input-space image.",
        "source": "Bundled CIFAR-100 sample; real LeNet/DLG execution through app.run_attack. Generated by scripts/generate_learning_demo.py.",
    }
    destination = ROOT / "frontend/src/data/learning-demo.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(example, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(f"Recorded teaching example: {destination}")


if __name__ == "__main__":
    main()
